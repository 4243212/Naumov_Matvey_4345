#include <iostream>
#include <string>
#include <vector>
#include <fstream>
int main() {
    std::ofstream log("log2.txt");
    log << "--- Проверка на циклический сдвиг (алгоритм КМП) ---\n";

    std::ios_base::sync_with_stdio(false);
    std::cin.tie(NULL);

    std::string t, p;
    if (!(std::cin >> t >> p)) {
        return 0;
    }

    log << "Считана строка A (t): '" << t << "'\n";
    log << "Считана строка B (p): '" << p << "'\n\n";

    int n = p.length();
    int m = t.length();

    log << "Длина строки A (m) = " << m << "\n";
    log << "Длина строки B (n) = " << n << "\n\n";

    log << "--- Построение префикс-функции для строки p ---\n";
    std::vector<int> pref(n, 0);
    log << "Инициализация массива pref нулями. Длина массива: " << n << "\n";

    for (int i = 1; i < n; ++i) {
        log << "\nИтерация i=" << i << ", текущий символ p[" << i << "] = '" << p[i] << "'\n";
        int j = pref[i - 1];
        log << "  Начальное значение j (из pref[" << i - 1 << "]): " << j << "\n";

        while (p[i] != p[j] && j > 0) {
            log << "  Несовпадение: p[" << i << "] ('" << p[i] << "') != p[" << j << "] ('" << p[j] << "')\n";
            log << "  Откат j к pref[" << j - 1 << "]\n";
            j = pref[j - 1];
            log << "  Новое значение j = " << j << "\n";
        }
        if (p[i] != p[j]) {
            log << "  Совпадений нет, j остается равным " << j << "\n";
            pref[i] = 0;
        } else {
            log << "  Совпадение: p[" << i << "] == p[" << j << "] ('" << p[i] << "'). Увеличиваем j.\n";
            pref[i] = j + 1;
        }
        log << "  -> Записываем pref[" << i << "] = " << pref[i] << "\n";

        log << "  Текущий массив pref: [";
        for (int k = 0; k < n; ++k) {
            log << pref[k] << (k == n - 1 ? "" : ", ");
        }
        log << "]\n";
    }

    if (n != t.length()) {
        log << "Длины строк не совпадают (n != m). Циклический сдвиг невозможен. Возврат -1.\n";
        log.close();
        std::cout << -1 << "\n";
        return 0;
    }

    log << "\n--- Поиск первого вхождения p в виртуальный текст t+t (КМП) ---\n";
    int j = 0;
    log << "Начальная длина совпадения j = 0\n";

    for (int i = 0; i < (2 * t.length() - 1); ++i) {
        log << "\nИтерация по тексту i=" << i << ", текущий символ t[" << i << " % " << n << "] = '" << t[i % n] << "'\n";
        log << "  Текущая длина совпадения j = " << j << "\n";

        while (t[i % n] != p[j] && j > 0) {
            log << "  Несовпадение: t[" << i << " % " << n << "] ('" << t[i % n] << "') != p[" << j << "] ('" << p[j] << "')\n";
            log << "  Откат j к pref[" << j - 1 << "]\n";
            j = pref[j - 1];
            log << "  Новое значение j = " << j << "\n";
        }
        if (t[i % n] == p[j]) {
            log << "  Совпадение: t[" << i << " % " << n << "] == p[" << j << "] ('" << t[i % n] << "'). Увеличиваем j.\n";
            j += 1;
            if (j == n) {
                log << "  !!! Найдено полное вхождение строки p (j == " << n << "). Индекс начала (сдвиг): " << (i - n + 1) << "\n";
                log << "--- Завершение алгоритма (успех) ---\n";
                log.close();
                std::cout << i - n + 1 << "\n";
                return 0;
            }
        } else {
            log << "  Совпадений нет, j остается равным " << j << "\n";
        }
    }

    log << "\nВхождение строки p в циклическую строку t не найдено.\n";
    log << "--- Завершение алгоритма (неудача) ---\n";
    log.close();
    std::cout << -1 << "\n";
    return 0;
}